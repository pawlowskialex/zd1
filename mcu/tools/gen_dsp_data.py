#!/usr/bin/env python3
"""Generate mcu/src/dsp_data.c from the ADAU1445 data extracted from the stock MCU apps (re/scripts/extract_dsp.py):
each model's download sequence (re/mcu/extracted/dsp/: ZD1 2.04.05, which the ZD1L's 2.04.35 sends byte for byte;
re/mcu/extracted/dsp-a7/: A7 2.04.77) and the runtime tables (re/mcu/extracted/dsp/runtime_tables.txt: the volume and
bass tables, the same bytes in the A7 app).

    python3 -I mcu/tools/gen_dsp_data.py      rewrites mcu/src/dsp_data.c"""

import os
import re
import struct
import zlib

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
EX = ROOT + "/re/mcu/extracted/"
OUT = ROOT + "/mcu/src/dsp_data.c"
# model -> (its download's directory, what it came from)
MODELS = {"zd1": ("dsp", "ZD1 2.04.05, = ZD1L 2.04.35"), "a7": ("dsp-a7", "A7 2.04.77")}


def download(d):
    seq = open(EX + d + "/download_sequence.bin", "rb").read()
    recs, i = [], 0
    while i < len(seq):
        addr, ln = struct.unpack(">HH", seq[i : i + 4])
        recs.append((addr, seq[i + 4 : i + 4 + ln]))
        i += 4 + ln
    return recs


rt = open(EX + "dsp/runtime_tables.txt").read()
vol = [int(m, 16) for m in re.findall(r"^idx\s+\d+: 0x([0-9a-f]{8})", rt, re.M)]
bass = [[int(x, 16) for x in re.findall(r"0x([0-9a-f]{8})\(", l)] for l in rt.splitlines() if l.startswith("entry ")]
assert len(vol) == 72 and len(bass) == 5 and all(len(b) == 5 for b in bass), (len(vol), len(bass))


def carr(name, data):
    lines = [", ".join("0x%02x" % b for b in data[j : j + 16]) for j in range(0, len(data), 16)]
    return "static const uint8_t %s[%d] = {\n    %s\n};\n" % (name, max(len(data), 1), ",\n    ".join(lines) or "0")


o = [
    "/* GENERATED by mcu/tools/gen_dsp_data.py from re/mcu/extracted/ (the stock apps' DSP setups) -- do not edit. */",
    '#include "dsp_data.h"',
    "",
]
for model, (d, what) in MODELS.items():
    recs = download(d)
    o.append("/* --- %s: %s, %d writes --- */\n" % (model, what, len(recs)))
    for n, (a, b) in enumerate(recs):
        o.append("/* step %d: subaddr 0x%04x, %d bytes, crc32 %08x */" % (n, a, len(b), zlib.crc32(b) & 0xFFFFFFFF))
        o.append(carr("%s_step%02d" % (model, n), b))
    o.append("const dsp_rec_t dsp_download_%s[] = {" % model)
    o += ["    { 0x%04x, %5d, %s_step%02d }," % (a, len(b), model, n) for n, (a, b) in enumerate(recs)]
    o.append("};")
    o.append("const unsigned dsp_download_%s_steps = %d;\n" % (model, len(recs)))
o.append("/* master volume, DSP index 0..71 (+10 dB .. -60 dB in 1 dB steps, 71 = mute), 5.23 -> param 0x4B */")
o.append(
    "const uint32_t dsp_volume_coef[72] = {\n    "
    + ",\n    ".join(", ".join("0x%08x" % v for v in vol[j : j + 6]) for j in range(0, 72, 6))
    + "\n};\n"
)
o.append('/* bass presets 0..4 (stock labels "Bass 0/+1/-1/-2/-3"), biquad b0 b1 b2 a1 a2 -> params 0x3F..0x43 */')
o.append(
    "const uint32_t dsp_bass_coef[5][5] = {\n"
    + ",\n".join("    { " + ", ".join("0x%08x" % v for v in b) + " }" for b in bass)
    + "\n};"
)
open(OUT, "w").write("\n".join(o) + "\n")
print("wrote %s" % OUT)
